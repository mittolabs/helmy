import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:helmy/data/repositories/conversation_repository_engines.dart';
import 'package:helmy/data/repositories/session_repository_local.dart';
import 'package:helmy/data/services/engines/engine_registry.dart';
import 'package:helmy/data/services/engines/engine_router.dart';
import 'package:helmy/data/services/engines/usage_meter.dart';
import 'package:helmy/data/services/history_import.dart';
import 'package:helmy/data/services/storage_service.dart';
import 'package:helmy/domain/models/chat_item.dart';
import 'package:helmy/ui/import/history_import_view_model.dart';

void main() {
  late Directory home;
  late Directory project;

  void write(String path, List<Map<String, Object?>> lines) {
    File('${home.path}/$path')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(lines.map(jsonEncode).join('\n'));
  }

  Map<String, Object?> user(
    Object content, {
    String entry = 'cli',
    bool meta = false,
    bool side = false,
  }) => {
    'type': 'user',
    'cwd': project.path,
    'entrypoint': entry,
    'isMeta': meta,
    'isSidechain': side,
    'uuid': 'u${content.hashCode}',
    'timestamp': '2026-11-01T10:00:00Z',
    'message': {'role': 'user', 'content': content},
  };

  Map<String, Object?> assistant(List<Map<String, Object?>> content) => {
    'type': 'assistant',
    'cwd': project.path,
    'uuid': 'a${content.hashCode}',
    'timestamp': '2026-11-01T10:01:00Z',
    'message': {'role': 'assistant', 'content': content},
  };

  Map<String, Object?> codexLine(String type, Map<String, Object?> payload) => {
    'timestamp': '2026-11-02T09:00:00Z',
    'type': type,
    'payload': payload,
  };

  setUp(() async {
    home = await Directory.systemTemp.createTemp('history');
    project = Directory('${home.path}/work/site')..createSync(recursive: true);
    // A conversation a person had in Claude Code.
    write('.claude/projects/-work-site/c1.jsonl', [
      user('<command-name>/clear</command-name>'),
      user('Caveat: the messages below were generated by the user', meta: true),
      user('Make the home page dark'),
      assistant([
        {'type': 'thinking', 'thinking': '...'},
        {'type': 'text', 'text': 'Reading it first.'},
        {
          'type': 'tool_use',
          'id': 't1',
          'name': 'Read',
          'input': {'file_path': 'index.html'},
        },
      ]),
      user([
        {'type': 'tool_result', 'tool_use_id': 't1', 'content': '<html></html>'},
      ]),
      user('a subagent asks', side: true),
      assistant([
        {'type': 'text', 'text': 'Done: it is dark now.'},
      ]),
      {'type': 'ai-title', 'aiTitle': 'Dark home page', 'sessionId': 'c1'},
    ]);
    // A program running Claude Code (as Helmy does): not brought in.
    write('.claude/projects/-work-site/c2.jsonl', [user('Run the checks', entry: 'sdk-cli')]);
    // Another account's conversation.
    write('.claude-work/projects/-work-site/c3.jsonl', [user('Second account question')]);
    // A Codex conversation, its instructions injected as the user's.
    write('.codex/sessions/2026/11/02/rollout-x.jsonl', [
      codexLine('session_meta', {'id': 'x1', 'cwd': project.path, 'originator': 'codex-tui'}),
      codexLine('response_item', {
        'type': 'message',
        'role': 'user',
        'content': [
          {'type': 'input_text', 'text': '# AGENTS.md instructions for the folder'},
        ],
      }),
      codexLine('response_item', {
        'type': 'message',
        'role': 'user',
        'content': [
          {'type': 'input_text', 'text': '<environment_context>cwd</environment_context>'},
        ],
      }),
      codexLine('response_item', {
        'type': 'message',
        'role': 'user',
        'content': [
          {'type': 'input_text', 'text': 'List the files'},
        ],
      }),
      codexLine('response_item', {
        'type': 'function_call',
        'name': 'shell',
        'call_id': 'f1',
        'arguments': jsonEncode({
          'command': ['bash', '-lc', 'ls'],
        }),
      }),
      codexLine('response_item', {
        'type': 'function_call_output',
        'call_id': 'f1',
        'output': jsonEncode({'output': 'index.html\n'}),
      }),
      codexLine('response_item', {
        'type': 'custom_tool_call',
        'name': 'apply_patch',
        'call_id': 'f2',
        'input': '*** Begin Patch\n*** Update File: index.html\n@@\n*** End Patch',
      }),
      codexLine('response_item', {
        'type': 'message',
        'role': 'assistant',
        'content': [
          {'type': 'output_text', 'text': 'One file: index.html.'},
        ],
      }),
    ]);
    // Helmy's own Codex run, and one in a scratch folder: not brought in.
    write('.codex/sessions/2026/11/02/rollout-h.jsonl', [
      codexLine('session_meta', {'id': 'h1', 'cwd': project.path, 'originator': 'helmy'}),
    ]);
    write('.codex/sessions/2026/11/02/rollout-t.jsonl', [
      codexLine('session_meta', {
        'id': 't1',
        'cwd': '/private/tmp/probe',
        'originator': 'codex-tui',
      }),
      codexLine('response_item', {
        'type': 'message',
        'role': 'user',
        'content': [
          {'type': 'input_text', 'text': 'hello'},
        ],
      }),
    ]);
  });
  tearDown(() => home.delete(recursive: true));

  test('finds what people said, by folder, from every account; not programs or scratch', () async {
    final found = await HistoryImport(home: home.path, scratch: const ['/private/tmp/']).scan();
    expect(found.single.cwd, project.path);
    expect(found.single.kinds, {'claude', 'codex'});
    final ids = {for (final c in found.single.conversations) '${c.engineId}:${c.threadId}'};
    expect(ids, {'claude:c1', 'claude-work:c3', 'codex:x1'});

    // What Helmy already has is left out.
    final again = await HistoryImport(
      home: home.path,
      scratch: const ['/private/tmp/'],
    ).scan(known: {'c1', 'x1'});
    expect({for (final c in again.single.conversations) c.threadId}, {'c3'});
  });

  test("a Claude Code conversation comes in as said: the person's words, steps and title", () {
    final lines = File('${home.path}/.claude/projects/-work-site/c1.jsonl').readAsLinesSync();
    final r = claudeConversation(lines);
    expect(r.title, 'Dark home page');
    expect([for (final i in r.items.whereType<UserMessage>()) i.text], ['Make the home page dark']);
    expect(
      [for (final i in r.items.whereType<AssistantText>()) i.text],
      ['Reading it first.', 'Done: it is dark now.'],
    );
    final step = r.items.whereType<ToolCall>().single;
    expect((step.name, step.result), ('Read', '<html></html>'));
  });

  test('a Codex conversation comes in with its steps named as Helmy names them', () {
    final lines = File('${home.path}/.codex/sessions/2026/11/02/rollout-x.jsonl').readAsLinesSync();
    final r = codexConversation(lines);
    expect([for (final i in r.items.whereType<UserMessage>()) i.text], ['List the files']);
    expect(r.title, 'List the files');
    final steps = r.items.whereType<ToolCall>().toList();
    expect(
      (steps[0].name, steps[0].input['command'], steps[0].result),
      ('Shell', 'ls', 'index.html\n'),
    );
    expect((steps[1].name, steps[1].input['file_path']), ('Edit', 'index.html'));
  });

  test('brought in, each is a session that goes on in its own thread, once', () async {
    final root = await Directory.systemTemp.createTemp('helmy');
    addTearDown(() => root.delete(recursive: true));
    final storage = StorageService(root: () async => root);
    final sessions = SessionRepositoryLocal(storage);
    final meter = UsageMeter();
    final repo = ConversationRepositoryEngines(
      engines: EngineRegistry([]),
      router: HeadroomRouter(meter),
      meter: meter,
      storage: storage,
      sessions: sessions,
    );
    final vm = HistoryImportViewModel(
      import: HistoryImport(home: home.path, scratch: const ['/private/tmp/']),
      sessions: sessions,
      conversations: repo,
    );
    addTearDown(vm.dispose);
    // Last touched a month ago: not chosen to start with.
    final old = DateTime.now().subtract(const Duration(days: 30));
    for (final f in home.listSync(recursive: true).whereType<File>()) {
      f.setLastModifiedSync(old);
    }
    await vm.load();
    expect(vm.chosen, isEmpty, reason: 'older than two weeks: not chosen to start with');
    vm.chooseAll(true);
    expect(vm.chosenConversations, 3);
    expect(await vm.importChosen(), 3);

    final dark = sessions.sessions.firstWhere((s) => s.title == 'Dark home page');
    expect(dark.cwd, project.path);
    expect(dark.threads['claude']?.resumeId, 'c1');
    final items = repo.of(dark.id).items;
    expect(dark.threads['claude']?.seen, items.length - 1, reason: 'all but the note');
    expect((items.last as Notice).text, HistoryImportViewModel.note);
    expect(
      items.last.toString(),
      isNot(contains('Claude')),
      reason: 'never named in a conversation',
    );
    expect(
      sessions.sessions.firstWhere((s) => s.threads.containsKey('claude-work')).title,
      'Second account question',
    );

    // Brought in once: nothing left to bring in.
    expect(vm.projects, isEmpty);
  });
}
